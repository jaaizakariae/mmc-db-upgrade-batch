CREATE TABLE VIZOR_INTEGRATION (
    ID           NUMBER(19, 0)     NOT NULL,
    FILENAME     VARCHAR2(500 CHAR),
    XML_CONTENT  CLOB              NOT NULL,
    RECEIVED_AT  TIMESTAMP(6)      NOT NULL,
    CONSTRAINT PK_VIZOR_INTEGRATION PRIMARY KEY (ID)
);

CREATE SEQUENCE VIZOR_INTEGRATION_SEQ
    START WITH 1
    INCREMENT BY 1
    CACHE 20;