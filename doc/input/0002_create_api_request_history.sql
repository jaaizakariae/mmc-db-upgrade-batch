CREATE TABLE MMC.API_REQUEST_HISTORY (
    ID              NUMBER(19, 0) NOT NULL,
    CLIENT_ID       VARCHAR2(500 CHAR),
    HTTP_METHOD     VARCHAR2(32 CHAR) NOT NULL,
    REQUEST_PATH    VARCHAR2(1000 CHAR) NOT NULL,
    HTTP_STATUS     NUMBER(3, 0) NOT NULL,
    RECEIVED_AT     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    DURATION_MS     NUMBER(19, 0) NOT NULL,
    ERROR_DESCRIPTION VARCHAR2(2000 CHAR),
    FILE_NAME       VARCHAR2(500 CHAR),
    REMOTE_ADDRESS  VARCHAR2(100 CHAR),
    CONSTRAINT PK_API_REQUEST_HISTORY PRIMARY KEY (ID)
);

CREATE SEQUENCE MMC.API_REQUEST_HISTORY_SEQ
    START WITH 1
    INCREMENT BY 1
    CACHE 20;